CREATE TABLE messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    load_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    load_amount NUMERIC(20, 2) NOT NULL,
    load_currency VARCHAR(3) NOT NULL,
    payload VARCHAR NOT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'NEW',
    accepted BOOLEAN,
    locked_until TIMESTAMP,
    claim_id UUID,
    attempt_count INT NOT NULL DEFAULT 0
);

CREATE TABLE customer_state (
    customer_id BIGINT PRIMARY KEY,
    locked_until TIMESTAMP,
    lock_token UUID,
    last_load_timestamp TIMESTAMP,
    total_loads_day NUMERIC(20, 2) NOT NULL DEFAULT 0,
    total_loads_week NUMERIC(20, 2) NOT NULL DEFAULT 0,
    count_loads_day INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_messages_queue
    ON messages (customer_id, status, received_at, message_id);
